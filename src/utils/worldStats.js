export function populationOf(id) {
  return (POP_K[String(id)] || 0) * 1000
}

export function totalPopulation() {
  let n = 0
  for (const v of Object.values(POP_K)) n += v
  return n * 1000
}

// Per-continent breakdown of {visited, total} counts. Visited counts items
// from `cats` where category === 'visited' or any user-defined "visited-like"
// category. Caller decides which catId counts as "visited" — we keep it
// generic by accepting an optional `visitedCatIds` set; default = ["visited"].
import { CONTINENT_BY_ID } from './continents'

export function continentBreakdown(cats, visitedCatIds = new Set(['visited'])) {
  const totals = { Africa: 0, Europe: 0, Asia: 0, 'North America': 0, 'South America': 0, Oceania: 0 }
  const visited = { Africa: 0, Europe: 0, Asia: 0, 'North America': 0, 'South America': 0, Oceania: 0 }
  // Build totals from continent table.
  for (const cont of Object.values(CONTINENT_BY_ID)) {
    if (cont in totals) totals[cont]++
  }
  for (const [id, catId] of Object.entries(cats || {})) {
    if (!visitedCatIds.has(catId)) continue
    const cont = CONTINENT_BY_ID[String(id)]
    if (cont && cont in visited) visited[cont]++
  }
  return Object.keys(totals).map((k) => ({
    continent: k,
    visited: visited[k],
    total: totals[k],
    pct: totals[k] ? (visited[k] / totals[k]) * 100 : 0,
  }))
}
